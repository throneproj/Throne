var (
	alpha3To2 = make(map[string]string)
	alpha2    = make(map[string]bool)
)

func init() {
	for _, entry := range strings.Fields(isoCountries) {
		alpha3To2[entry[:3]] = entry[3:]
		alpha2[entry[3:]] = true
	}
}

// NormalizeRegion maps an alpha-2 or alpha-3 country code to alpha-2; "" when it names no country
// (XX, ZZ, EU, Cloudflare's T1 for Tor...).
func NormalizeRegion(code string) string {
	code = strings.ToUpper(strings.TrimSpace(code))
	switch len(code) {
	case 2:
		if alpha2[code] {
			return code
		}
	case 3:
		return alpha3To2[code]
	}
	return ""
}
